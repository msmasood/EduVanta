function Merge-LandingSections {
  param([string]$FilePath, [string]$NewSectionsJson)
  
  $content = Get-Content $FilePath -Raw -Encoding UTF8
  $root = $content | ConvertFrom-Json
  $newSections = $NewSectionsJson | ConvertFrom-Json
  
  # Add each new section to root.landing
  foreach ($prop in $newSections.PSObject.Properties) {
    if ($root.landing.PSObject.Properties[$prop.Name]) {
      Write-Host "  Skipping existing key: $($prop.Name)"
    } else {
      $root.landing | Add-Member -NotePropertyName $prop.Name -NotePropertyValue $prop.Value
      Write-Host "  Added: $($prop.Name)"
    }
  }
  
  # Write back with proper formatting
  $output = $root | ConvertTo-Json -Depth 20 -Compress:$false
  # Ensure UTF-8 without BOM
  [System.IO.File]::WriteAllText($FilePath, $output, [System.Text.UTF8Encoding]::new($false))
  Write-Host "Saved $FilePath"
}

